const NotifyFailureTypeMDADMDegraded = "MDADMDegraded"

type MDADMPayload struct {
	ArrayUUID      string
	ArrayName      string
	ArrayLevel     string
	State          string
	ActiveDevices  int
	WorkingDevices int
	FailedDevices  int
	SpareDevices   int

	Date        string
	FailureType string
	Subject     string
	Message     string
}

func NewMDADMDegradedPayload(array models.MDADMArray, metrics colmodels.MDADMMetrics) MDADMPayload {
	payload := MDADMPayload{
		ArrayUUID:      array.UUID,
		ArrayName:      array.Name,
		ArrayLevel:     array.Level,
		State:          metrics.State,
		ActiveDevices:  metrics.ActiveDevices,
		WorkingDevices: metrics.WorkingDevices,
		FailedDevices:  metrics.FailedDevices,
		SpareDevices:   metrics.SpareDevices,
		Date:           time.Now().Format(time.RFC3339),
		FailureType:    NotifyFailureTypeMDADMDegraded,
	}

	payload.Subject = payload.generateSubject()
	payload.Message = payload.generateMessage()
	return payload
}

func (p *MDADMPayload) generateSubject() string {
	return fmt.Sprintf("Scrutiny RAID Degradation (%s) detected on array: %s", p.FailureType, p.ArrayName)
}

func (p *MDADMPayload) generateMessage() string {
	messageParts := []string{
		fmt.Sprintf("Scrutiny RAID Degradation notification for array: %s", p.ArrayName),
		fmt.Sprintf("Array UUID: %s", p.ArrayUUID),
		fmt.Sprintf("RAID Level: %s", p.ArrayLevel),
		fmt.Sprintf("Array State: %s", p.State),
		fmt.Sprintf("Active Devices: %d", p.ActiveDevices),
		fmt.Sprintf("Working Devices: %d", p.WorkingDevices),
		fmt.Sprintf("Failed Devices: %d", p.FailedDevices),
		fmt.Sprintf("Spare Devices: %d", p.SpareDevices),
		"",
		fmt.Sprintf(fmtDate, p.Date),
	}

	return strings.Join(messageParts, "\n")
}

func NewMDADMNotify(logger logrus.FieldLogger, appconfig config.Interface, array models.MDADMArray, metrics colmodels.MDADMMetrics) Notify {
	mdadmPayload := NewMDADMDegradedPayload(array, metrics)

	// Convert to standard Payload structure for Send() functionality
	// It uses DeviceType/DeviceName to house Array details to avoid altering the base payload.
	payload := Payload{
		DeviceType:   "MDADM",
		DeviceName:   array.Name,
		DeviceSerial: array.UUID,
		DeviceLabel:  fmt.Sprintf("RAID %s", array.Level),
		Test:         false,
		Date:         mdadmPayload.Date,
		FailureType:  mdadmPayload.FailureType,
		Subject:      mdadmPayload.Subject,
		Message:      mdadmPayload.Message,
	}
	payload.HTMLMessage = formatNotificationHTML(
		payload.Subject,
		"Scrutiny RAID degradation notification",
		"RAID DEGRADED",
		"#dc3545",
		[][2]string{
			{"Failure Type", mdadmPayload.FailureType},
			{"Array Name", mdadmPayload.ArrayName},
			{"Array UUID", mdadmPayload.ArrayUUID},
			{"RAID Level", mdadmPayload.ArrayLevel},
			{"Array State", mdadmPayload.State},
			{"Active Devices", fmt.Sprintf("%d", mdadmPayload.ActiveDevices)},
			{"Working Devices", fmt.Sprintf("%d", mdadmPayload.WorkingDevices)},
			{"Failed Devices", fmt.Sprintf("%d", mdadmPayload.FailedDevices)},
			{"Spare Devices", fmt.Sprintf("%d", mdadmPayload.SpareDevices)},
			{"Date", mdadmPayload.Date},
		},
		"Generated by Scrutiny",
	)

	return Notify{
		Logger:  logger,
		Config:  appconfig,
		Payload: payload,
	}
}

// MDADMTracker remembers, per array, the degradation last announced, so an array that stays
// degraded is not announced again on every collection unless repeat notifications are on. Like
// the other notification dedup state it lives in memory: a restart announces each degraded
// array once more.
type MDADMTracker struct {
	notified map[string]mdadmDegradation
	mu       sync.Mutex
}

type mdadmDegradation struct {
	active int
	failed int
}

func NewMDADMTracker() *MDADMTracker {
	return &MDADMTracker{notified: make(map[string]mdadmDegradation)}
}

// Evaluate announces a degraded array when repeat is on, when nothing has been announced for
// it yet, or when it lost an active member or gained a failed one since the last announcement.
// send reports whether the notification was delivered or queued. Only then is it recorded, so a
// failed delivery is retried on the next collection instead of being lost.
func (t *MDADMTracker) Evaluate(uuid string, metrics *colmodels.MDADMMetrics, repeat bool, send func() bool) {
	current := mdadmDegradation{active: metrics.ActiveDevices, failed: metrics.FailedDevices}

	t.mu.Lock()
	previous, announced := t.notified[uuid]
	worse := !announced || current.failed > previous.failed || current.active < previous.active
	if !repeat && !worse {
		// Same or better than announced: keep the current shape as the baseline, so losing a
		// member again later is announced.
		t.notified[uuid] = current
		t.mu.Unlock()
		return
	}
	t.mu.Unlock()

	// Sent outside the lock so a slow notification service does not stall other arrays. Two
	// concurrent uploads for one array can both announce; collectors upload an array serially.
	if send() {
		t.mu.Lock()
		t.notified[uuid] = current
		t.mu.Unlock()
	}
}

// Forget clears the record once an array is healthy, so its next degradation is announced.
func (t *MDADMTracker) Forget(uuid string) {
	t.mu.Lock()
	delete(t.notified, uuid)
	t.mu.Unlock()
}
